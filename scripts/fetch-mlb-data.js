/* One-time (well, once-a-season) data fetch. Pulls real 2025 game-by-game
 * hitting logs for a curated list of well-known players, plus full team
 * standings, from MLB's official free Stats API (no key required), and
 * writes the trimmed result to data/mlb-2025.js as a plain JS file so the
 * app can load it with a <script> tag (no fetch()/CORS needed at runtime).
 *
 * Re-run next season: bump SEASON below and re-run `node scripts/fetch-mlb-data.js`.
 */
const fs = require('fs');
const path = require('path');

const SEASON = 2025;

const PLAYERS = [
  { id: 592450, name: 'Aaron Judge', team: 'New York Yankees' },
  { id: 660271, name: 'Shohei Ohtani', team: 'Los Angeles Dodgers' },
  { id: 677951, name: 'Bobby Witt Jr.', team: 'Kansas City Royals' },
  { id: 665742, name: 'Juan Soto', team: 'New York Mets' },
  { id: 518692, name: 'Freddie Freeman', team: 'Los Angeles Dodgers' },
  { id: 605141, name: 'Mookie Betts', team: 'Los Angeles Dodgers' },
  { id: 660670, name: 'Ronald Acuña Jr.', team: 'Atlanta Braves' },
  { id: 514888, name: 'Jose Altuve', team: 'Houston Astros' },
  { id: 665489, name: 'Vladimir Guerrero Jr.', team: 'Toronto Blue Jays' },
  { id: 663656, name: 'Kyle Tucker', team: 'Chicago Cubs' },
  { id: 596019, name: 'Francisco Lindor', team: 'New York Mets' },
  { id: 682998, name: 'Corbin Carroll', team: 'Arizona Diamondbacks' },
  { id: 683002, name: 'Gunnar Henderson', team: 'Baltimore Orioles' }
];

async function fetchJSON(url){
  const res = await fetch(url, { headers: { 'User-Agent': 'sports-math-curriculum-fetch/1.0' } });
  if(!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.json();
}

async function fetchPlayerGames(p){
  const url = `https://statsapi.mlb.com/api/v1/people/${p.id}/stats?stats=gameLog&group=hitting&season=${SEASON}`;
  const data = await fetchJSON(url);
  const splits = (data.stats && data.stats[0] && data.stats[0].splits) || [];
  const games = splits
    .map(s => ({
      hits: s.stat.hits,
      atBats: s.stat.atBats,
      homeRuns: s.stat.homeRuns,
      rbi: s.stat.rbi,
      strikeOuts: s.stat.strikeOuts
    }))
    .filter(g => g.atBats > 0); // skip games with no at-bats (pinch-run only, etc.)
  return { id: p.id, name: p.name, team: p.team, games };
}

async function fetchStandings(){
  const url = `https://statsapi.mlb.com/api/v1/standings?leagueId=103,104&season=${SEASON}`;
  const data = await fetchJSON(url);
  const teams = [];
  for(const record of data.records || []){
    for(const tr of record.teamRecords || []){
      teams.push({
        name: tr.team.name,
        wins: tr.leagueRecord.wins,
        losses: tr.leagueRecord.losses,
        pct: parseFloat(tr.leagueRecord.pct)
      });
    }
  }
  return teams;
}

async function main(){
  console.log(`Fetching ${SEASON} MLB data for ${PLAYERS.length} players...`);
  const players = [];
  for(const p of PLAYERS){
    process.stdout.write(`  ${p.name}... `);
    const entry = await fetchPlayerGames(p);
    console.log(`${entry.games.length} games`);
    players.push(entry);
  }
  console.log('Fetching standings...');
  const teams = await fetchStandings();
  console.log(`  ${teams.length} teams`);

  const out = `/* Auto-generated by scripts/fetch-mlb-data.js — real ${SEASON} MLB data. Do not hand-edit; re-run the script instead. */
const MLB_DATA = ${JSON.stringify({ season: SEASON, players, teams }, null, 0)};
`;
  const outPath = path.join(__dirname, '..', 'data', 'mlb-2025.js');
  fs.writeFileSync(outPath, out);
  console.log(`Wrote ${outPath} (${(out.length/1024).toFixed(1)} KB)`);
}

main().catch(err => { console.error(err); process.exit(1); });
