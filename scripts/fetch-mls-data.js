/* One-time (well, once-a-season) data fetch. Pulls real 2025 MLS standings
 * from balldontlie.io's free tier — Teams/Standings are free for MLS (unlike
 * NBA, where standings need a paid tier), so this is a single API call, no
 * pagination or derivation needed. Writes data/mls-2025.js as a plain JS
 * file so the app can load it with a <script> tag (no fetch()/CORS needed
 * at runtime).
 *
 * Requires BALLDONTLIE_API_KEY in the environment (see .env, gitignored).
 * Re-run next season: bump SEASON below, then run (bash):
 *   source <(grep -v '^#' .env | sed 's/^/export /') && node scripts/fetch-mls-data.js
 */
const fs = require('fs');
const path = require('path');

const SEASON = 2025;
const API_KEY = process.env.BALLDONTLIE_API_KEY;
if(!API_KEY){
  console.error('Set BALLDONTLIE_API_KEY in the environment first (see .env).');
  process.exit(1);
}

async function main(){
  console.log(`Fetching ${SEASON} MLS standings...`);
  const res = await fetch(`https://api.balldontlie.io/mls/v1/standings?season=${SEASON}`, {
    headers: { Authorization: API_KEY }
  });
  if(!res.ok) throw new Error(`${res.status} ${res.statusText}`);
  const data = await res.json();

  const teams = data.data.map(row => ({
    name: row.team.name,
    wins: row.wins,
    losses: row.losses,
    draws: row.draws,
    gamesPlayed: row.games_played,
    points: row.points,
    goalsFor: row.goals_for,
    goalsAgainst: row.goals_against
  }));
  console.log(`  ${teams.length} teams`);

  const out = `/* Auto-generated by scripts/fetch-mls-data.js — real ${SEASON} MLS standings
 * (balldontlie.io free tier). Do not hand-edit; re-run the script instead. */
const MLS_DATA = ${JSON.stringify({ season: SEASON, teams }, null, 0)};
`;
  const outPath = path.join(__dirname, '..', 'data', 'mls-2025.js');
  fs.writeFileSync(outPath, out);
  console.log(`Wrote ${outPath} (${(out.length/1024).toFixed(1)} KB)`);
}

main().catch(err => { console.error(err); process.exit(1); });
