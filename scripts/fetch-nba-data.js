/* One-time (well, once-a-season) data fetch. Pulls real 2024-25 NBA game
 * results from balldontlie.io's free tier (games + teams only — player
 * stats/season averages/standings all require a paid tier and returned
 * "Unauthorized" when checked) and derives, ourselves, each team's real
 * per-game point totals and win-loss record. Writes data/nba-2024.js as a
 * plain JS file so the app can load it with a <script> tag (no fetch()/CORS
 * needed at runtime).
 *
 * Requires BALLDONTLIE_API_KEY in the environment (see .env, gitignored).
 * Free tier is rate-limited to 5 requests/minute, so this deliberately
 * paces requests ~13s apart — expect it to take a few minutes.
 *
 * Re-run next season: bump SEASON below, then run (bash):
 *   source <(grep -v '^#' .env | sed 's/^/export /') && node scripts/fetch-nba-data.js
 */
const fs = require('fs');
const path = require('path');

const SEASON = 2024;
const API_KEY = process.env.BALLDONTLIE_API_KEY;
if(!API_KEY){
  console.error('Set BALLDONTLIE_API_KEY in the environment first (see .env).');
  process.exit(1);
}

const BASE = 'https://api.balldontlie.io/v1';
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function fetchJSON(url){
  const res = await fetch(url, { headers: { Authorization: API_KEY } });
  if(!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.json();
}

async function fetchAllGames(season){
  const games = [];
  let cursor = null;
  for(;;){
    const url = `${BASE}/games?seasons[]=${season}&per_page=100${cursor ? `&cursor=${cursor}` : ''}`;
    const data = await fetchJSON(url);
    games.push(...data.data);
    process.stdout.write(`  fetched ${games.length} games...\r`);
    if(!data.meta || !data.meta.next_cursor) break;
    cursor = data.meta.next_cursor;
    await sleep(13000); // stay under the 5 req/min free-tier limit
  }
  console.log(`  fetched ${games.length} games total.`);
  return games.filter(g => g.status === 'Final' && !g.postseason);
}

function deriveTeamData(teams, games){
  const byTeam = {};
  for(const t of teams) byTeam[t.id] = { id: t.id, name: t.full_name, games: [], wins: 0, losses: 0 };

  for(const g of games){
    const home = byTeam[g.home_team.id];
    const visitor = byTeam[g.visitor_team.id];
    if(home){
      const win = g.home_team_score > g.visitor_team_score;
      home.games.push({ points: g.home_team_score, win });
      win ? home.wins++ : home.losses++;
    }
    if(visitor){
      const win = g.visitor_team_score > g.home_team_score;
      visitor.games.push({ points: g.visitor_team_score, win });
      win ? visitor.wins++ : visitor.losses++;
    }
  }
  return Object.values(byTeam).filter(t => t.games.length > 0);
}

async function main(){
  console.log('Fetching NBA teams...');
  const teamsData = await fetchJSON(`${BASE}/teams?per_page=100`);
  const teams = teamsData.data;
  console.log(`  ${teams.length} teams`);

  await sleep(13000);
  console.log(`Fetching ${SEASON}-${(SEASON+1)%100} season games...`);
  const games = await fetchAllGames(SEASON);

  const teamData = deriveTeamData(teams, games);
  console.log(`Derived per-game data for ${teamData.length} teams.`);

  const out = `/* Auto-generated by scripts/fetch-nba-data.js — real ${SEASON}-${(SEASON+1)%100} NBA
 * data (games + teams from balldontlie.io's free tier; per-game team
 * points and win-loss records derived from raw game results ourselves,
 * since player stats/standings need a paid tier). Do not hand-edit;
 * re-run the script instead. */
const NBA_DATA = ${JSON.stringify({ season: SEASON, teams: teamData }, null, 0)};
`;
  const outPath = path.join(__dirname, '..', 'data', 'nba-2024.js');
  fs.writeFileSync(outPath, out);
  console.log(`Wrote ${outPath} (${(out.length/1024).toFixed(1)} KB)`);
}

main().catch(err => { console.error(err); process.exit(1); });
